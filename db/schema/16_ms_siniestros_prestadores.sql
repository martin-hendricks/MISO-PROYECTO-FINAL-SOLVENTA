-- Catálogo de prestadores (red de atención de siniestros).
-- Idempotente: las tablas se crean si faltan y la semilla no duplica filas.

CREATE TABLE IF NOT EXISTS ms_siniestros.prestador (
    id               TEXT          PRIMARY KEY CHECK (id ~ '^PRE-[A-Z0-9-]+$'),
    nombre           TEXT          NOT NULL CHECK (char_length(nombre) BETWEEN 1 AND 120),
    tipo             TEXT          NOT NULL CHECK (tipo IN (
                         'servicio-tecnico', 'taller-motos', 'ips-urgencias', 'grua',
                         'asistencia-viajero', 'punto-aeropuerto', 'ips-examenes',
                         'funeraria', 'centro-atencion')),
    direccion        TEXT          NOT NULL CHECK (char_length(direccion) BETWEEN 1 AND 200),
    ciudad           TEXT          NOT NULL CHECK (ciudad IN ('Bogotá', 'Medellín', 'Chía')),
    barrio           TEXT          NOT NULL CHECK (char_length(barrio) BETWEEN 1 AND 80),
    lat              NUMERIC(9,6)  NOT NULL CHECK (lat BETWEEN -90 AND 90),
    lng              NUMERIC(9,6)  NOT NULL CHECK (lng BETWEEN -180 AND 180),
    telefono         TEXT          NOT NULL CHECK (char_length(telefono) BETWEEN 1 AND 40),
    horario          TEXT          NOT NULL CHECK (char_length(horario) BETWEEN 1 AND 80),
    estado           TEXT          NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo', 'inactivo')),
    creado_por       TEXT          NOT NULL,
    creado_en        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_por  TEXT          NOT NULL,
    actualizado_en   TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ms_siniestros.prestador_ramo (
    prestador_id  TEXT NOT NULL REFERENCES ms_siniestros.prestador(id),
    ramo          TEXT NOT NULL,
    PRIMARY KEY (prestador_id, ramo)
);

CREATE INDEX IF NOT EXISTS ix_prestador_estado_geo ON ms_siniestros.prestador (estado, lat, lng);
CREATE INDEX IF NOT EXISTS ix_prestador_ciudad ON ms_siniestros.prestador (ciudad, estado);
CREATE INDEX IF NOT EXISTS ix_prestador_ramo_ramo ON ms_siniestros.prestador_ramo (ramo, prestador_id);

